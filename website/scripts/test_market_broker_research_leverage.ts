import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {calculatePerpsResearch,MAX_RESEARCH_LEVERAGE,REAL_KRAKEN_TEST_LEVERAGE_CAP,REAL_KRAKEN_FIRST_TEST_NOTIONAL_USD} from '../src/services/perpsResearch';

assert.equal(MAX_RESEARCH_LEVERAGE,20);
assert.equal(REAL_KRAKEN_TEST_LEVERAGE_CAP,2);
assert.equal(REAL_KRAKEN_FIRST_TEST_NOTIONAL_USD,10);
const long=calculatePerpsResearch({marginUsd:100,leverage:10,entryPrice:100000,side:'LONG',favorableMovePct:2,adverseMovePct:1});
assert.equal(long.valid,true);
assert.equal(long.notionalUsd,1000);
assert.equal(long.favorablePnlUsd,20);
assert.equal(long.adversePnlUsd,-10);
assert.equal(long.favorablePrice,102000);
assert.equal(long.adversePrice,99000);
assert.equal(long.theoreticalMarginExhaustionMovePct,10);
assert.equal(long.theoreticalMarginExhaustionPrice,90000);
assert.equal(long.marginRiskPctAtAdverseMove,10);
assert.equal(long.adverseMoveExceedsMargin,false);
assert.match(long.caution,/NOT the venue liquidation price/);
const short=calculatePerpsResearch({marginUsd:100,leverage:10,entryPrice:100000,side:'SHORT',favorableMovePct:2,adverseMovePct:1});
assert.equal(short.favorablePrice,98000);
assert.equal(short.adversePrice,101000);
assert.ok(Math.abs((short.theoreticalMarginExhaustionPrice||0)-110000)<0.000001);
assert.equal(short.favorablePnlUsd,20);
assert.equal(short.adversePnlUsd,-10);
const risky=calculatePerpsResearch({marginUsd:100,leverage:20,entryPrice:100000,side:'LONG',favorableMovePct:2,adverseMovePct:6});
assert.equal(risky.adverseMoveExceedsMargin,true);
assert.equal(risky.theoreticalMarginExhaustionMovePct,5);
assert.equal(risky.adversePnlUsd,-120);
const absent=calculatePerpsResearch({marginUsd:100,leverage:8,entryPrice:null,side:'LONG',favorableMovePct:2,adverseMovePct:1});
assert.equal(absent.valid,false);
assert.equal(absent.favorablePnlUsd,null);
assert.equal(absent.theoreticalMarginExhaustionPrice,null);
const clamped=calculatePerpsResearch({marginUsd:100,leverage:500,entryPrice:100,side:'SHORT',favorableMovePct:2,adverseMovePct:1});
assert.equal(clamped.leverage,20);
const backend=readFileSync('server/migrated_backend.ts','utf8');
assert.ok(backend.includes('leverage>2'),'Kraken manual test preview 2x cap is unchanged');
assert.ok(backend.includes('Number(p.leverage)>2'),'Kraken manual test submission 2x cap is unchanged');
const broker=readFileSync('server/market_broker.ts','utf8');
assert.ok(broker.includes('calculatePerpsResearch('));
assert.ok(broker.includes('researchScenario'));
assert.ok(broker.includes('This endpoint cannot place or prepare orders'));
const screen=readFileSync('src/components/MarketBrokerScreen.tsx','utf8');
assert.ok(screen.includes('MAX_RESEARCH_LEVERAGE'));
assert.ok(screen.includes('theoreticalMarginExhaustionPrice'));
assert.ok(screen.includes('REAL_KRAKEN_TEST_LEVERAGE_CAP'));
console.log('PASS: isolated Perps 1x–20x research, long/short P&L, margin exhaustion caution and unchanged real Kraken execution caps.');
